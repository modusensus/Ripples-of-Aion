/**
 * 实体属性别名归一化（v0.3.0）。
 *
 * 为什么需要：claim 的闭合与时间轴查询都按属性字面量精确匹配，而 LLM
 * 每轮选词可能不同（生产实测「工作所在地」vs「工作地点」、「出差行程」
 * vs「行程」）——同一事实换了字面量，旧 claim 不被闭合，时间轴上出现
 * 两条并存的有效声明。归一化把变体收敛到 canonical 词条，让比较一律
 * 「看 canonical」：存量数据保留原字面量、新增数据落库即 canonical，
 * 老数据不用迁移也能正确闭合与合并时间轴。
 *
 * 保守原则：只做确定性的精确别名替换，不做模糊/包含匹配；语义不同的
 * 属性绝不合并（宁可漏归一不可错归一），无命中时原样返回。
 */

/**
 * canonical 属性词表：抽取 prompt 引导 LLM 优先使用的封闭集合。
 * extractor 与下方别名映射的取值共用这一份（单一事实源），
 * 别名映射的 value 必须都是词表内的词条。
 */
export const CANONICAL_ATTRS: readonly string[] = [
  "所在地",
  "居住地",
  "工作地点",
  "职位",
  "雇主",
  "日程",
  "行程",
  "偏好",
  "关系",
  "健康状况",
  "姓名",
  "联系方式",
];

/**
 * 别名映射表（清洗后的精确匹配查表）：key 是变体，value 是 canonical 词条。
 * 只收录语义完全等同的变体，两个刻意不合并的边界：
 * - 「所在地」（当下在哪，可能临时出差）≠「居住地」（常住哪）；
 * - 「职业」（干什么行当）≠「职位」（具体岗位）。
 */
const ATTR_ALIASES: ReadonlyMap<string, string> = new Map([
  // 生产实测案例（v0.2.0 线上出现的两处字面量漂移）
  ["工作所在地", "工作地点"],
  ["出差行程", "行程"],
  // 居住地系
  ["住址", "居住地"],
  ["家庭住址", "居住地"],
  ["现居地", "居住地"],
  ["现居住地", "居住地"],
  // 所在地系
  ["当前位置", "所在地"],
  ["现所在地", "所在地"],
  // 雇主系
  ["工作单位", "雇主"],
  ["公司", "雇主"],
  // 职位系
  ["职务", "职位"],
  // 日程/行程系
  ["日程安排", "日程"],
  ["行程安排", "行程"],
  // 偏好/健康系
  ["喜好", "偏好"],
  ["健康", "健康状况"],
  ["健康状态", "健康状况"],
  ["身体状态", "健康状况"],
  // 姓名/关系系
  ["名字", "姓名"],
  ["关系状态", "关系"],
]);

/**
 * 属性名归一化：trim + 全角转半角 + 去掉全部内部空白，再查别名表。
 * 幂等（canonical 形式再过一遍不变）、无副作用、空串/纯空白安全。
 * 非字符串入参返回空串：claim 字段是 LLM 派生数据，重放时类型不可信，
 * 空串只会比较不命中，天然 fail-safe。
 */
export function canonicalAttr(attr: string): string {
  if (typeof attr !== "string") return "";
  let cleaned = "";
  for (const ch of attr) {
    const code = ch.codePointAt(0) ?? 0;
    if (code === 0x3000) {
      cleaned += " "; // 全角空格并入普通空白，下面统一去掉
    } else if (code >= 0xff01 && code <= 0xff5e) {
      cleaned += String.fromCharCode(code - 0xfee0); // 全角 ASCII 区转半角
    } else {
      cleaned += ch;
    }
  }
  // 属性是短标签，内部空白只会是噪声（含换行/制表），全部去掉
  cleaned = cleaned.trim().replace(/\s+/g, "");
  // 精确查表；无命中保持清洗后的原样，不猜测语义
  return ATTR_ALIASES.get(cleaned) ?? cleaned;
}
